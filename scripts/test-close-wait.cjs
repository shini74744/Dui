const fs = require('fs'), vm = require('vm'), assert = require('assert');
const root = require('path').resolve(__dirname, '..');
const source = fs.readFileSync(root + '/web/html/xray.html', 'utf8');
const start = source.indexOf('      normalizeXrayPolicy(form) {');
const end = source.indexOf('      async loadXrayConnectionPolicy()', start);
assert(start >= 0 && end > start);
const methods = vm.runInNewContext('({' + source.slice(start, end) + '})');
const original = {policy:{levels:{'0':{bufferSize:64}},system:{statsInboundUplink:true}},routing:{domainStrategy:'AsIs'}};
const form = {handshake:4,connIdle:300,uplinkOnly:0,downlinkOnly:0,closeWaitTimeout:30};
let saved = JSON.parse(methods.mergeXrayPolicyText(JSON.stringify(original), form));
assert.equal(saved.policy.system.duiCloseWaitTimeout, 30);
assert.equal(saved.policy.system.statsInboundUplink, true);
assert.equal(saved.policy.levels['0'].bufferSize, 64);
methods.xrayPolicyForm = form;
methods.xrayPolicySavedForm = methods.normalizeXrayPolicy(form);
assert(methods.xrayPolicySaved());
methods.xrayPolicyForm = {...form,closeWaitTimeout:60};
assert(!methods.xrayPolicySaved());
saved = JSON.parse(methods.mergeXrayPolicyText(JSON.stringify(saved), {...form,closeWaitTimeout:0}));
assert(!Object.hasOwn(saved.policy.system,'duiCloseWaitTimeout'));
assert.equal(saved.policy.system.statsInboundUplink,true);
assert.equal(methods.normalizeXrayPolicy({}).closeWaitTimeout,0);
console.log('CLOSE-WAIT form: persistence, dirty state, disable and unrelated fields passed');
